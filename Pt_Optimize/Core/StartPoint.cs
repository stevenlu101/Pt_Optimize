namespace PtOptimize.Core;

/// <summary>
/// **五个优化变量的初始值** —— 唯一来源。
///
/// ★ 用户 2026-08-25 定的边界：
///   「这些是优化变量：板厚 / 舌保温 / 环倍率 / 管保温 / 夹持温度，
///     优化程式需自己给出答案（能造能用，优化铂金量），**可以在 UI 输入框上给初始值**。」
///   同一天更强的一条：「**把种子这种方法彻底禁掉，定案檔是用来校正计算流程，不应当被乱用。**」
///
/// ⇒ 这五项的起点**不许来自定案档**。定案档只留两种正当用途：
///   ① 工程师**明确点「载入定案」**时灌进控件（校正计算流程：载入 → 核算 → 对得上）；
///   ② 判据表对照、回归基准、自检门的活样本。
///
/// ★★ 病灶（本类为它而建）：本页此前**没有舌保温与环倍率的控件**，
///   于是 `PageToFinalDesign` 从 <c>FinalDesign.Current</c> 继承 ——
///   而 `Current` 全仓**只在声明处赋过值**（恒为 W08）。
///   后果：点「载入定案」选 0.6 档，控件都变成 0.6 的值，**舌保温却仍是 0.8 档的**
///   （W08 = 0.4/0.4/**0.5**/**0.3**，W06 = 0.4/0.4/**0.4**/**0.6**）
///   ⇒ 算的是「0.6 的管 + 0.8 的保温」，而界面还写着「点核算整线就能复现定案数字」。
///
/// ⚠ 每个初始值都必须**说得出依据**（用户禁掉 `--seedflat` 的理由就是「自己捏的数」）。
///   下面四项的依据逐条写在各自的注释里。板厚**没有**统一初始值 ——
///   它在解析模式由界面控件给、在 .3dm 模式由图纸给，两者都是真实输入。
/// </summary>
public static class StartPoint
{
    /// <summary>
    /// 舌保温起点 mm = <see cref="SizerOptions.InsLoMm"/>（旋钮自己的下界）。
    /// **依据**：0.3 mm ≈ **裸舌**，是一个真实物理状态（没包纤维的舌片），不是捏的数。
    /// 且它在省铂方向的**保守侧**：保温越少，从管子抽的热越多、②′ 越不容易变负。
    /// </summary>
    public const double TabInsulMm = 0.3;

    /// <summary>
    /// 环倍率起点 = <see cref="SizerOptions.RingLo"/>。
    /// **依据**：1.00 = **无台阶**（管孔周围不加厚），同样是真实状态 —— 就是一片平板。
    /// </summary>
    public const double RingMul = 1.00;

    /// <summary>
    /// 管保温起点 mm。
    ///
    /// ★★★★★ **这个数没有第一性原理依据 —— 必须说明白，不许包装。**
    ///
    /// 我最初给它写的「依据」是「界面那个框一直以来的初始值」。
    /// 那不是依据，那只是**它一直在那儿**。用户 2026-08-25 明确要求：
    /// 「这是要交付工程师的项目，**所有都必须是算出来的**（必须严格遵守第一性原理），
    ///   不要为交差而走歪路。」—— 拿一个 UI 默认值包装成「声明式默认」，正是走歪路。
    ///
    /// **实情**：用户把管保温列进「优化变量」（优化程式需自己给出答案），
    /// 但 <see cref="Sizer"/> 主循环**只调三个旋钮**（板厚／舌保温／环倍率），
    /// 管保温它一个都不动 ⇒ 今天它是**被钉死的输入**，起点即终点，**从来没被算过**。
    ///
    /// ⇒ 这个 10.0 是一个**占位值**，唯一的作用是让程序跑得起来。
    ///   它会被 `--tubeins` 或界面控件覆盖，且**每次都必须印出来**。
    ///   真正的修法是给 D8 加上这个旋钮，让它由「能造能用 + 省铂」解出来。
    /// </summary>
    public const double TubeInsulMm = 10.0;

    /// <summary>
    /// 铜排夹持温度起点 °C。
    ///
    /// ★★★★★ **同样没有第一性原理依据，同样是占位值。**
    ///
    /// 而且这一项比管保温更该被算出来：夹持温度是**热平衡的结果**——
    /// 舌片往铜排导的热，减去铜排带走的热，稳定下来就是那个温度。
    /// 把它当成一个**给定的数**，等于把一个未知量当成了已知量。
    ///
    /// ⚠ <see cref="DesignInputs"/> 里已经写着另一条路：
    ///   「≥0 时**取代** BusbarClampTempC 的二选一，改用**第三边界**：
    ///     q = G·(T_舌端 − T_冷端)」—— 那才是第一性原理的写法：
    ///   给铜排一个导热系数 G 与冷端温度，夹持温度**自己解出来**。
    ///   本项目已经有那个机制，只是这条路没走它。
    /// </summary>
    public const double ClampTempC = 300.0;
}
